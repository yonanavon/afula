/** אייקון לפי סוג העסק. משמש כשאין תמונה בעמודת "תמונה". */
const TYPE_ICONS = [
  [/פיצ(ר|ה)/, '🍕'],
  [/מאפי|קונדיטור|לחם/, '🥐'],
  [/פלאפל|חומוס/, '🧆'],
  [/גליד|גלד/, '🍦'],
  [/קפה|מסעד/, '🍽️'],
  [/מזנון|צ׳יפס|צ'יפס/, '🥙'],
  [/מרכול|סופר|מכולת/, '🛒'],
  [/פיצוח|תבלינ|אגוז/, '🥜'],
  [/ממתק|פינוק|שוקולד/, '🍫'],
];

export function iconForType(type = '') {
  const match = TYPE_ICONS.find(([pattern]) => pattern.test(type));
  return match ? match[1] : '🍴';
}

/**
 * פיצול תא רב-ערכי ("פרווה, חלבי") לרשימה נקייה.
 * מיועד לעמודת הקטגוריה בלבד — שדות ההשגחה נשארים כטקסט חופשי, כדי לא
 * לשבור ניסוח כמו "בד״צ העדה החרדית ו/או הרב לנדא" לשני תגים ולרמוז בטעות
 * ששניהם נדרשים יחד.
 */
export function splitList(value = '') {
  return String(value)
    .split(/[,،\/|]/)
    .map((part) => part.trim())
    .filter(Boolean);
}
